"""Conservative single-camera shuttle landing review for the local Web UI.

This is intentionally *not* an official Hawk-Eye system.  An official line
call needs synchronised, calibrated high-speed cameras and a 3-D flight
reconstruction.  The local pipeline has one camera, a 2-D court homography,
and a measured shuttle track.  We therefore review only the terminal flight
of a rally and publish a result when a measured motion-to-rest landing event
is present.  A last-seen/airborne endpoint is not a landing and produces no
coordinate or line distance.  Anything close to a line is deliberately left
as ``review``.

The module is separated from the renderer so the conservative evidence rules
can be unit-tested from a CSV-shaped list of rows.
"""

